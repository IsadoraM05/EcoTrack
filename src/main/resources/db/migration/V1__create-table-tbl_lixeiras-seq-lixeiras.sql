CREATE SEQUENCE SEQ_LIXEIRAS
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE TABLE TBL_LIXEIRAS(
    LIXEIRA_ID INTEGER DEFAULT SEQ_LIXEIRAS.NEXTVAL NOT NULL,
    TIPO_RESIDUO VARCHAR2(10) NOT NULL,
    CAPACIDADE_MAXIMA NUMBER(9,2) NOT NULL,
    NIVEL_ATUAL NUMBER(9,2) NOT NULL,
    STATUS VARCHAR2(50) NOT NULL,
    CONSTRAINT PK_TBL_LIXEIRAS PRIMARY KEY (LIXEIRA_ID)
);