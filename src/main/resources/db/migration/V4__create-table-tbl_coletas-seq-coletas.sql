CREATE SEQUENCE SEQ_COLETAS
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE TABLE TBL_COLETAS (
    COLETA_ID INTEGER DEFAULT SEQ_COLETAS.NEXTVAL NOT NULL,
    QUANTIDADE_COLETADA NUMBER(9,2) NOT NULL,
    DATA_COLETA TIMESTAMP NOT NULL,
    RESPONSAVEL VARCHAR2(100) NOT NULL,
    DESTINO VARCHAR2(150) NOT NULL,
    LIXEIRA_ID INTEGER NOT NULL,

    CONSTRAINT PK_TBL_COLETAS
        PRIMARY KEY (COLETA_ID),

    CONSTRAINT FK_COLETAS_LIXEIRAS
        FOREIGN KEY (LIXEIRA_ID)
        REFERENCES TBL_LIXEIRAS(LIXEIRA_ID)
);