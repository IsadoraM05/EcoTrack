CREATE SEQUENCE SEQ_ALERTAS
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE TABLE TBL_ALERTAS (
    ALERTA_ID INTEGER DEFAULT SEQ_ALERTAS.NEXTVAL NOT NULL,
    MENSAGEM VARCHAR2(255) NOT NULL,
    NIVEL_ALERTA VARCHAR2(50) NOT NULL,
    DATA_CRIACAO TIMESTAMP NOT NULL,
    RESOLVIDO NUMBER(1) DEFAULT 0 NOT NULL,
    LIXEIRA_ID INTEGER NOT NULL,

    CONSTRAINT PK_TBL_ALERTAS
        PRIMARY KEY (ALERTA_ID),

    CONSTRAINT FK_ALERTAS_LIXEIRAS
        FOREIGN KEY (LIXEIRA_ID)
        REFERENCES TBL_LIXEIRAS(LIXEIRA_ID)
);