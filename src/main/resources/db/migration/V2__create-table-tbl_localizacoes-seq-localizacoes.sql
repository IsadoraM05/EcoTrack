CREATE SEQUENCE SEQ_LOCALIZACOES
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE TABLE TBL_LOCALIZACOES (
    LOCALIZACAO_ID INTEGER DEFAULT SEQ_LOCALIZACOES.NEXTVAL NOT NULL,
    NOME VARCHAR2(100) NOT NULL,
    TIPO_LOCAL VARCHAR2(50) NOT NULL,
    ENDERECO VARCHAR2(200) NOT NULL,

    CONSTRAINT PK_TBL_LOCALIZACOES PRIMARY KEY (LOCALIZACAO_ID)
);